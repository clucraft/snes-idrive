/* the pictures: 8 x 8 */
const TILES = {
    0x01: ['........', '.xxxxxx.', '.xxxxxx.', '.xxxxxx.', '.xxxxxx.', '.xxxxxx.', '.xxxxxx.', '........'],   // a light, on
    0x02: ['#.......', '#.......', '#.......', '#.......', '#.......', '#.......', '#.......', '########'],   // the picture's corners: bottom left
    0x03: ['.......#', '.......#', '.......#', '.......#', '.......#', '.......#', '.......#', '########'],   // bottom right
    0x04: ['########', '#.......', '#.......', '#.......', '#.......', '#.......', '#.......', '#.......'],   // top left
    0x05: ['########', '.......#', '.......#', '.......#', '.......#', '.......#', '.......#', '.......#'],   // top right
    0x06: ['........', '........', '........', 'o.o.o.o.', '........', '........', '........', '........'],   // the ball's track
};
const BALL = ['..xxxx..', '.xxxxxx.', 'xx#xxxxx', 'x#xxxxxx', 'xxxxxxxx', 'xxxxxxxx', '.xxxxxx.', '..xxxx..'];

const PIXEL = { '.': 0, '#': 1, o: 2, x: 3 };

/** a tile's rows -> its bytes, planes bits a pixel: the SNES keeps two planes together, a row of each in turn */
function tile(rows, planes) {
    const out = Buffer.alloc(planes * 8);
    rows.forEach((row, y) => {
        for (let x = 0; x < 8; x++) {
            const c = PIXEL[row[x]];
            if (c === undefined) throw new Error('a pixel "' + row[x] + '" in ' + rows.join(' '));
            if (c & 1) out[y * 2] |= 0x80 >> x;
            if (c & 2) out[y * 2 + 1] |= 0x80 >> x;
        }
    });
    return out;
}

function build() {
    const font = Buffer.alloc(96 * 16);
    Object.keys(TILES).forEach((n) => {
        const rows = TILES[n];
        if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error('tile ' + n + ' is not 8 x 8');
        tile(rows, 2).copy(font, n * 16);
    });
    Object.keys(FONT).forEach((ch) => {
        const rows = FONT[ch], n = ch.charCodeAt(0);
        if (n < 0x20 || n > 0x5f || rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error('letter ' + ch + ' is not 5 x 7, or has no tile');
        tile(rows.map((r) => '.' + r + '..').concat(['........']), 2).copy(font, n * 16);
    });
    return { font, ball: tile(BALL, 4) };
}

if (require.main === module) {
    if (!process.argv[2]) { console.error('usage: node mkchr.js <folder>'); process.exit(1); }
    const b = build();
    fs.writeFileSync(path.join(process.argv[2], 'font.bin'), b.font);
    fs.writeFileSync(path.join(process.argv[2], 'ball.bin'), b.ball);
}
module.exports = { build };
